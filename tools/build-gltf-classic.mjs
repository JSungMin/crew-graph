#!/usr/bin/env node
// Turns three.js r158's ES-module GLTFLoader into a classic script that uses the global THREE
// (the viewer runs from file://, where `<script type="module">` is blocked).
//
//   node tools/build-gltf-classic.mjs [--three <dir of an unpacked three@0.158.0 package>]
//
// Without --three it runs `npm pack three@0.158.0` in a temp folder and unpacks that.
// Output: plugins/crew-graph/web/gltf-loader.classic.js   (three.js is MIT, see third_party/three-LICENSE.txt)
// What it does to examples/jsm/loaders/GLTFLoader.js:
//   - the `import { ... } from 'three'` list becomes `const { ... } = THREE;`
//   - the one helper it needs from BufferGeometryUtils (toTrianglesDrawMode) is copied in by name
//   - `export { GLTFLoader }` becomes `THREE.GLTFLoader = GLTFLoader;`
// Nothing else is touched, so the result is the stock loader.
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const VERSION = '0.158.0'
const here = dirname(fileURLToPath(import.meta.url))
const out = resolve(here, '../plugins/crew-graph/web/gltf-loader.classic.js')

const argAt = process.argv.indexOf('--three')
let pkg = argAt > 0 ? resolve(process.argv[argAt + 1]) : ''
if (!pkg) {
  const tmp = mkdtempSync(join(tmpdir(), 'three-'))
  const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm'
  execFileSync(npm, ['pack', `three@${VERSION}`, '--silent'], { cwd: tmp, shell: process.platform === 'win32', stdio: 'inherit' })
  execFileSync('tar', ['-xzf', `three-${VERSION}.tgz`, 'package/package.json', 'package/examples/jsm/loaders/GLTFLoader.js', 'package/examples/jsm/utils/BufferGeometryUtils.js'], { cwd: tmp, stdio: 'inherit' })
  pkg = join(tmp, 'package')
}

const version = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8')).version
if (version !== VERSION) throw new Error(`expected three@${VERSION}, found ${version}`)

const src = readFileSync(join(pkg, 'examples/jsm/loaders/GLTFLoader.js'), 'utf8')
const utils = readFileSync(join(pkg, 'examples/jsm/utils/BufferGeometryUtils.js'), 'utf8')

const imp = /^import \{([\s\S]*?)\} from 'three';\n/m.exec(src)
if (!imp) throw new Error('no `import {...} from "three"` in GLTFLoader.js')
const names = imp[1].split(',').map(s => s.trim()).filter(Boolean)

const helperAt = utils.indexOf('function toTrianglesDrawMode(')
if (helperAt < 0) throw new Error('toTrianglesDrawMode not found')
const helperEnd = utils.indexOf('\n}\n', helperAt)
const helper = utils.slice(helperAt, helperEnd + 3)

let body = src
  .replace(imp[0], '')
  .replace(/^import \{ toTrianglesDrawMode \} from '..\/utils\/BufferGeometryUtils.js';\n/m, '')
if (!/^export \{ GLTFLoader \};\s*$/m.test(body)) throw new Error('export { GLTFLoader } not found')
body = body.replace(/^export \{ GLTFLoader \};\s*$/m, 'THREE.GLTFLoader = GLTFLoader;\n')

const text = `/*
 * three.js r${VERSION.split('.')[1]} examples/jsm/loaders/GLTFLoader.js as a classic script (uses the global THREE).
 * Generated by tools/build-gltf-classic.mjs, do not edit. Sets THREE.GLTFLoader.
 * Draco, Meshopt and KTX2 are not wired up: a glTF that requires them will not load.
 *
 * three.js: Copyright 2010-2023 three.js authors, MIT License (third_party/three-LICENSE.txt).
 */
(function () {
'use strict';
const {
\t${names.join(',\n\t')}
} = THREE;

${helper}
${body}
})();
`
writeFileSync(out, text)
console.log(`wrote ${out} (${text.length} bytes, ${names.length} THREE names)`)
